-- Transfer service database. Owned by this service only; other services' entities are
-- referenced by ID (account IDs), never by foreign key.

CREATE TABLE transfers (
    id                     UUID           PRIMARY KEY,
    idempotency_key        VARCHAR(100)   NOT NULL UNIQUE,
    source_account_id      VARCHAR(64)    NOT NULL,
    destination_account_id VARCHAR(64)    NOT NULL,
    amount                 NUMERIC(19, 2) NOT NULL CHECK (amount > 0),
    currency               VARCHAR(3)     NOT NULL,
    status                 VARCHAR(20)    NOT NULL,
    compensate_from        VARCHAR(30),
    failure_kind           VARCHAR(20),
    failure_code           VARCHAR(60),
    failure_message        VARCHAR(500),
    failure_http_status    INTEGER,
    notification_status    VARCHAR(20)    NOT NULL,
    created_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    updated_at             TIMESTAMP WITH TIME ZONE NOT NULL,
    version                BIGINT         NOT NULL,
    CONSTRAINT chk_transfers_different_accounts CHECK (source_account_id <> destination_account_id)
);

-- The recovery job looks for non-terminal transfers that have not moved for a while
CREATE INDEX idx_transfers_status_updated ON transfers (status, updated_at);

-- Challenge 2. The primary key is what makes two simultaneous requests with the same key safe:
-- the database lets exactly one INSERT win. This row is inserted before the transfer row in the
-- same transaction, so there is deliberately no foreign key to transfers.
CREATE TABLE idempotency_keys (
    idempotency_key VARCHAR(100)  PRIMARY KEY,
    request_hash    VARCHAR(64)   NOT NULL,
    transfer_id     UUID          NOT NULL,
    status          VARCHAR(20)   NOT NULL,
    response_code   INTEGER,
    response_body   VARCHAR(8000),
    created_at      TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at    TIMESTAMP WITH TIME ZONE
);

-- Audit trail of every saga step and compensation (evidence for Challenge 3C)
CREATE TABLE saga_steps (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transfer_id UUID         NOT NULL REFERENCES transfers (id),
    step        VARCHAR(30)  NOT NULL,
    action      VARCHAR(20)  NOT NULL,
    outcome     VARCHAR(20)  NOT NULL,
    detail      VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_saga_steps_transfer ON saga_steps (transfer_id, id);
